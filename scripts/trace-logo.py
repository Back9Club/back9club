"""Trace public/brand/back9club-logo-original.png into src/brand/logo-paths.ts.

Splits the artwork into its white and green layers, upscales 8x so the traced
curves are smooth, and vectorises each layer with potrace (apt install potrace).
Usage: python3 scripts/trace-logo.py
"""

import pathlib
import re
import subprocess
import tempfile

import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "public/brand/back9club-logo-original.png"
OUT = ROOT / "src/brand/logo-paths.ts"
SCALE = 8


def main() -> None:
    im = Image.open(SRC).convert("RGB").crop((71, 126, 438, 314))
    big = np.asarray(
        im.resize((im.width * SCALE, im.height * SCALE), Image.LANCZOS), dtype=np.int16
    )
    r, g, b = big[..., 0], big[..., 1], big[..., 2]
    green = (g - np.maximum(r, b)) > 55
    white = (np.minimum(np.minimum(r, g), b) > 118) & ~green
    # The "Est 2026" stamp is only 3px tall in the source: drop it and re-set
    # it as live text (see LOGO_STAMP) instead of tracing a blur.
    white[1340:1384, 1392:1584] = False

    paths = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name, mask in (("white", white), ("green", green)):
            pbm = pathlib.Path(tmp) / f"{name}.pbm"
            svg = pathlib.Path(tmp) / f"{name}.svg"
            Image.fromarray(np.where(mask, 0, 255).astype(np.uint8)).convert("1").save(pbm)
            subprocess.run(
                ["potrace", str(pbm), "-s", "-o", str(svg), "-t", "40", "-a", "1.1", "-O", "0.4", "--flat"],
                check=True,
            )
            found = re.findall(r'<path d="([^"]+)"', svg.read_text(), re.S)
            paths[name] = " ".join(p.replace("\n", " ") for p in found)

    OUT.write_text(
        f"""// Generated by tracing the supplied Back 9 Club logo (scripts/trace-logo.py).
// Paths use potrace's coordinate space: apply LOGO_PATH_TRANSFORM.
export const LOGO_VIEWBOX = {{ width: 2936, height: 1504 }} as const;
export const LOGO_PATH_TRANSFORM = "translate(0,1504) scale(0.1,-0.1)";
// The logo's own green (sampled from the artwork).
export const LOGO_GREEN = "#27B936";
// Position of the small "Est 2026" stamp, re-set as live text.
export const LOGO_STAMP = {{ x: 1488, y: 1376, width: 176, fontSize: 33 }} as const;
export const LOGO_WHITE_PATH =
  "{paths['white']}";
export const LOGO_GREEN_PATH =
  "{paths['green']}";
"""
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
